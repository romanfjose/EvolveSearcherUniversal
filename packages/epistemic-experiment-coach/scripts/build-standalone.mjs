// Builds docs/index.html: one self-contained page (no network, no dependencies) from src/core + src/standalone.
// Usage: node scripts/build-standalone.mjs [--check]   (--check exits 1 if docs/index.html is stale)
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const OUTPUT = path.join(root, "docs", "index.html");
// Dependency order: each module may only reference modules listed before it.
export const SOURCES = ["src/core/domains.mjs", "src/core/journey.mjs", "src/core/calibration.mjs", "src/standalone/app.js"];

/** Turns an ES module into plain statements for a shared scope: drops imports, unwraps `export`. */
export function stripModuleSyntax(source, name = "module") {
  const out = source.replace(/^import\s[^;]+;[ \t]*\n/gm, "").replace(/^export\s+(?=(?:const|let|function|class|async)\b)/gm, "");
  const leftover = out.match(/^\s*(?:import|export)\b.*$/m);
  if (leftover) throw new Error(`${name}: unsupported module syntax: ${leftover[0].trim()}`);
  return out;
}

export async function buildStandalone() {
  const { CSS } = await import(pathToFileURL(path.join(root, "src/core/styles.mjs")).href);
  const parts = await Promise.all(SOURCES.map(async (file) => `// ── ${file}\n${stripModuleSyntax(await readFile(path.join(root, file), "utf8"), file)}`));
  const script = `(() => {\n"use strict";\n${parts.join("\n")}\n})();`;
  if (/<\/script/i.test(script) || /<\/style/i.test(CSS)) throw new Error("Inlined code must not contain a closing script/style tag");
  return `<!doctype html>
<!-- GENERATED by scripts/build-standalone.mjs from src/core/ and src/standalone/app.js. Do not edit by hand. -->
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="description" content="Turn vague resistance into one small, falsifiable reality test. Runs entirely in your browser.">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; img-src data:; base-uri 'none'; form-action 'none'">
<title>Clash with Reality</title>
<style>${CSS}</style>
</head>
<body>
<div id="root" class="ee-root"></div>
<noscript><p style="padding:24px;font-family:system-ui">Clash with Reality needs JavaScript; it runs entirely in your browser and sends nothing anywhere.</p></noscript>
<script>
${script}
</script>
</body>
</html>
`;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const html = await buildStandalone();
  if (process.argv.includes("--check")) {
    const current = await readFile(OUTPUT, "utf8").catch(() => "");
    if (current !== html) { console.error("docs/index.html is stale: run `npm run build:standalone`"); process.exit(1); }
    console.log("docs/index.html is up to date");
  } else {
    await writeFile(OUTPUT, html);
    console.log(`Wrote ${path.relative(root, OUTPUT)} (${(Buffer.byteLength(html) / 1024).toFixed(1)} KiB)`);
  }
}
